"""Types for the persisted ``home/flow.json`` ledger document."""

from pathlib import Path
from typing import Final, Literal, NotRequired, Required, TypedDict, cast

#: flow.json field with the digest of the step results it was generated from.
STEP_RESULTS_DIGEST_FIELD: Final = "step_results_digest"


class ChecklistStatus(TypedDict, total=False):
    """The gate projection stored beside a step's checklist rows."""

    status: Literal["passed", "blocked", "attention", "unknown"]
    blocked: bool
    failed_items: list[str]
    source: str
    summary: dict
    requirements_status: Literal["none", "present"]
    revision: str
    updated_at: str


FlowStepEntry = TypedDict(
    "FlowStepEntry",
    {
        "name": Required[str],
        "tool": Required[str],
        "state": Required[str],
        "directory": NotRequired[str],
        "category": NotRequired[str],
        "input_step": NotRequired[str],
        "info": NotRequired[dict],
        "runtime": NotRequired[str],
        "peak memory (mb)": NotRequired[float | int],
        "checklist": NotRequired[list[dict]],
        "checklist_status": NotRequired[ChecklistStatus],
        "resource_observation": NotRequired[dict],
    },
)


class FlowDocument(TypedDict, total=False):
    """The ledger document; unknown keys read by the GUI are preserved."""

    steps: list[FlowStepEntry]
    schema_version: int
    options: dict
    step_results_digest: str


def load_flow_document(path: Path | None) -> FlowDocument:
    """Read a ledger; an absent or non-object document loads as an empty one.

    A workspace ledger generated by this ECC takes each step's results from its
    step directory (see ``chipcompiler.data.step.results``).
    """
    if path is None:
        return {}
    from chipcompiler.utility import json_read

    raw = json_read(path)
    if not isinstance(raw, dict):
        return {}
    workspace_directory = ledger_workspace_directory(path)
    if workspace_directory is not None:
        from chipcompiler.data.step.results import apply_step_results

        apply_step_results(raw, workspace_directory, digest_field=STEP_RESULTS_DIGEST_FIELD)
    return cast(FlowDocument, raw)  # Shape guards stay in the readers, not the loader.


def ledger_workspace_directory(path: Path | str) -> Path | None:
    """The workspace of a ``<workspace>/home/flow.json`` ledger; None for any other path."""
    path = Path(path)
    if path.name != "flow.json" or path.parent.name != "home":
        return None
    return path.parent.parent
